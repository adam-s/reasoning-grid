// Capture each figure as an image for readers who have JavaScript off.
//
//   npm run preview
//   node scripts/build-figure-stills.mjs [url]
//
// Writes public/figures/<name>.gif or .png, one per [data-fig] on the page.
//
// These are only ever fetched by a browser with scripting disabled: markup
// inside <noscript> is not parsed when scripting is on, so a normal reader
// never requests them and they cost nothing on the critical path. That is what
// makes it affordable to ship a megabyte of animation here.
//
// Animated where the figure animates, still where it does not. The script does
// not decide that from a list -- it captures frames and compares them, so a
// figure that gains or loses motion is handled without anyone remembering to
// update anything.
//
// Run against the PREVIEW, not the dev server. These images stand in for the
// figures that ship.
import { chromium } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const TARGET = process.argv[2] || 'http://localhost:4173/';
const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '../public/figures');
const TMP = join(here, '../.figure-frames');
const MANIFEST = join(here, '../src/lib/viz/figure-stills.ts');

// Ten frames at 160ms is 1.6 seconds of loop. Long enough to show what a figure
// does, short enough that nine of them are not a video library.
const FRAMES = 10;
const EVERY_MS = 160;

// Captured at this width and at 1x. The images stand in for a figure, they are
// not a substitute for looking at the real one, and a phone reader on a page
// with no JavaScript is the last person who wants a 2x asset.
const WIDTH = 900;

rmSync(TMP, { recursive: true, force: true });
mkdirSync(TMP, { recursive: true });
mkdirSync(OUT, { recursive: true });

const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: WIDTH, height: 900 } });
await page.goto(TARGET, { waitUntil: 'networkidle' });

const names = await page.evaluate(() =>
  [...document.querySelectorAll('[data-fig]')].map((el) => el.getAttribute('data-fig')),
);

const report = [];

for (const name of names) {
  const fig = page.locator(`[data-fig="${name}"]`);
  await fig.scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);

  // Anything with a play control gets pressed, so the capture shows the figure
  // doing its thing rather than sitting at rest.
  const play = fig.locator('button[aria-label="Play"]');
  if (await play.count()) {
    await play.first().click().catch(() => {});
    await page.waitForTimeout(400);
  }

  const frames = [];
  for (let i = 0; i < FRAMES; i++) {
    frames.push(await fig.screenshot());
    if (i < FRAMES - 1) await page.waitForTimeout(EVERY_MS);
  }

  const moves = frames.some((f) => !f.equals(frames[0]));

  if (!moves) {
    writeFileSync(join(OUT, `${name}.png`), frames[0]);
    report.push([name, 'png', statSync(join(OUT, `${name}.png`)).size]);
    continue;
  }

  const dir = join(TMP, name);
  mkdirSync(dir, { recursive: true });
  frames.forEach((f, i) => writeFileSync(join(dir, `${String(i).padStart(3, '0')}.png`), f));

  // Two passes so the palette is built from the whole clip rather than the
  // first frame. A single pass quantises the surface's ramp into bands.
  const palette = join(dir, 'palette.png');
  const fps = Math.round(1000 / EVERY_MS);
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-framerate', String(fps), '-i', join(dir, '%03d.png'),
    '-vf', 'palettegen=max_colors=128:stats_mode=diff', palette]);
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-framerate', String(fps), '-i', join(dir, '%03d.png'),
    '-i', palette, '-lavfi', 'paletteuse=dither=bayer:bayer_scale=3', '-loop', '0',
    join(OUT, `${name}.gif`)]);
  report.push([name, 'gif', statSync(join(OUT, `${name}.gif`)).size]);
}

await b.close();
rmSync(TMP, { recursive: true, force: true });

// A manifest rather than a prop on each <Figure>: the extension depends on
// whether the figure turned out to move, which this script decides by looking.
// Writing it down by hand would go stale the first time one of them gained an
// animation.
const entries = report.map(([name, kind]) => `  '${name}': '${name}.${kind}',`).join('\n');
writeFileSync(
  MANIFEST,
  `/**\n` +
    ` * GENERATED by scripts/build-figure-stills.mjs -- do not edit by hand.\n` +
    ` *\n` +
    ` * What each figure looks like, for a reader with JavaScript off. Animated\n` +
    ` * where the figure animates. Only ever fetched by that reader: markup inside\n` +
    ` * <noscript> is not parsed when scripting is on, so nobody else pays for it.\n` +
    ` */\nexport const FIGURE_STILLS: Record<string, string> = {\n${entries}\n};\n`,
);

let total = 0;
for (const [name, kind, size] of report) {
  total += size;
  console.log(`  ${name.padEnd(14)} ${kind}  ${(size / 1024).toFixed(0)}KB`);
}
console.log(`\n${report.length} figures, ${(total / 1024 / 1024).toFixed(2)}MB total (fetched only with JavaScript off)`);
